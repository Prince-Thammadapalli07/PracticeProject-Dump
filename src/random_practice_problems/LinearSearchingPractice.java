package random_practice_problems;

public class LinearSearchingPractice {
    static void main() {

        int x = 4;
        System.out.println(sqrt(x));
        System.out.println(8/1);
    }

    static int sqrt(int num) {
        int i = 1;
        while (i <= num / i) {
            i++;
        }
        return i-1;
    }
}
